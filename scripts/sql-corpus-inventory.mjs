#!/usr/bin/env node
/**
 * Phase 0/2 baseline: regex CTE counts for all .sql under TRACE_SQL_CORPUS_ROOT.
 * Usage: node scripts/sql-corpus-inventory.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const corpusRoot = process.env.TRACE_SQL_CORPUS_ROOT
  ? path.resolve(process.env.TRACE_SQL_CORPUS_ROOT)
  : path.join(repoRoot, 'tests/sql-corpus/fixtures');

const CTE_RE = /\bWITH\s+(?:RECURSIVE\s+)?([a-zA-Z_]\w*)\s+AS\s*\(/gim;

function walk(dir, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    if (ent.name.startsWith('.')) continue;
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, out);
    else if (ent.name.endsWith('.sql')) out.push(p);
  }
  return out;
}

if (!fs.existsSync(corpusRoot)) {
  console.error('Corpus not found:', corpusRoot);
  process.exit(1);
}

const files = walk(corpusRoot);
let cteSymbols = 0;
let filesWithCte = 0;
for (const f of files) {
  const text = fs.readFileSync(f, 'utf8');
  const m = text.match(CTE_RE);
  if (m?.length) {
    filesWithCte++;
    cteSymbols += m.length;
  }
}

const report = {
  trace_mcp_version: '3.34.6',
  extractor: 'regex-sql-plugin',
  corpus_root: corpusRoot,
  files: files.length,
  files_with_first_cte_match: filesWithCte,
  first_cte_symbol_count: cteSymbols,
  note: 'Counts only WITH-name-AS-( matches, not comma-separated CTEs',
};

const outPath = path.join(repoRoot, 'tests/sql-corpus/baseline-inventory.json');
fs.writeFileSync(
  outPath,
  `${JSON.stringify({ ...report, note: `${report.note}. Generated by scripts/sql-corpus-inventory.mjs.` }, null, 2)}\n`,
);
console.log(JSON.stringify(report, null, 2));
