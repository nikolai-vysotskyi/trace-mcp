#!/usr/bin/env node
/**
 * Generates docs/llms-full.txt by concatenating every page in docs/sitemap.xml.
 *
 * It used to be hand-maintained: 170 KB, no generator, and it drifted twice over
 * — four pages missing entirely and four more serving copies older than the live
 * page, while advertising itself as "full text of all docs pages" (TRA-681). A
 * stale full-text dump is worse than none: an AI system that ingests it gets
 * confidently wrong content with no signal that it is out of date.
 *
 * Run `pnpm docs:sitemap`, which runs this too; the guard in
 * tests/docs/internal-links.test.ts fails when the committed file is not what
 * this script would produce.
 *
 * ponytail: plain concatenation of the Markdown sources, no Jekyll render. The
 * output keeps its own front matter so GitHub Pages still expands the
 * `{{ site.data.* }}` tags the pages carry, exactly as the hand-written file did.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { sitemapSources } from './gen-sitemap.mjs';

const DOCS = join(import.meta.dirname, '..', 'docs');

const HEADER = `---
# Front matter only so Jekyll renders the {{ site.data.counts.* }} tags below
# (TRA-263). Stripped from the served file.
layout: null
---
{%- comment -%}
GENERATED by scripts/gen-llms-full.mjs — do not edit by hand. Edit the docs page.
{%- endcomment -%}
# trace-mcp — Full documentation

> Concatenated full text of all trace-mcp docs pages, for AI systems that ingest one file instead of following links. See /llms.txt for the linked index.
`;

/**
 * The page body as a reader gets it: no front matter, no JSON-LD (machine
 * metadata that says nothing a text ingester can use), no HTML comments.
 * `{{ page.updated }}` is resolved here — inside one concatenated file it would
 * otherwise resolve to llms-full's own front matter and date every page alike.
 */
export function pageBody(file) {
  const raw = readFileSync(join(DOCS, file), 'utf-8');
  const fm = raw.match(/^---\n([\s\S]*?)\n---\n/);
  const updated = fm?.[1].match(/^updated:[ \t]*(\S+)/m)?.[1] ?? '';
  return (fm ? raw.slice(fm[0].length) : raw)
    .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\n?/g, '')
    .replace(/<!--[\s\S]*?-->\n?/g, '')
    .replaceAll('{{ page.updated }}', updated)
    .trim();
}

export function build() {
  const xml = readFileSync(join(DOCS, 'sitemap.xml'), 'utf-8');
  const pages = sitemapSources(xml).filter((f) => f.endsWith('.md'));
  return [HEADER, ...pages.map((f) => `\n---\n\n${pageBody(f)}\n`)].join('');
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(join(DOCS, 'llms-full.txt'), build());
  console.log('docs/llms-full.txt regenerated from the pages in docs/sitemap.xml');
}
